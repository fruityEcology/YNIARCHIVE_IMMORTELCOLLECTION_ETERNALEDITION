#include "Main.h"
#include "Vector3.h"

//---------------------------------------------------------------------------------
//	コンストラクタ
//---------------------------------------------------------------------------------
Vector3::Vector3()
{
	x = 0.0f;
	y = 0.0f;
	z = 0.0f;
}
//---------------------------------------------------------------------------------
//	ゼロ初期化
//---------------------------------------------------------------------------------
void Vector3::clear()
{
	x = 0.0f;
	y = 0.0f;
	z = 0.0f;
}
//---------------------------------------------------------------------------------
//	セット
//---------------------------------------------------------------------------------
void Vector3::set(float x, float y, float z)
{
	this->x = x;
	this->y = y;
	this->z = z;
}
void Vector3::set(Vector3& v)
{
	x = v.x;
	y = v.y;
	z = v.z;
}
//---------------------------------------------------------------------------------
//	足し算
//---------------------------------------------------------------------------------
void Vector3::add(Vector3& v)
{
	x += v.x;
	y += v.y;
	z += v.z;
}
void Vector3::add(Vector3& v0, Vector3& v1)
{
	x = v0.x + v1.x;
	y = v0.y + v1.y;
	z = v0.z + v1.z;
}
void Vector3::add(float x, float y, float z)
{
	this->x += x;
	this->y += y;
	this->z += z;
}
//---------------------------------------------------------------------------------
//	引き算
//---------------------------------------------------------------------------------
void Vector3::subtract(Vector3& v)
{
	x -= v.x;
	y -= v.y;
	z -= v.z;
}
void Vector3::subtract(Vector3& v0, Vector3& v1)
{
	x = v0.x - v1.x;
	y = v0.y - v1.y;
	z = v0.z - v1.z;
}
//---------------------------------------------------------------------------------
//	掛け算
//---------------------------------------------------------------------------------
void Vector3::scale(float scale)
{
	x *= scale;
	y *= scale;
	z *= scale;
}
//---------------------------------------------------------------------------------
//	長さ取得
//---------------------------------------------------------------------------------
float Vector3::length()
{
	return sqrtf(x * x + y * y + z * z);
}
//---------------------------------------------------------------------------------
//	正規化
//---------------------------------------------------------------------------------
void Vector3::normalize()
{
	float len = length();
	if (len > 0.0f) {
		x = x / len;
		y = y / len;
		z = z / len;
	}
}
//---------------------------------------------------------------------------------
//	長さ設定
//---------------------------------------------------------------------------------
void Vector3::length(float len)
{
	normalize();
	x = x * len;
	y = y * len;
	z = z * len;
}
//---------------------------------------------------------------------------------
//	内積
//---------------------------------------------------------------------------------
float Vector3::dot(Vector3& v)
{
	return x * v.x + y * v.y + z * v.z;
}
float Vector3Dot(Vector3& v0, Vector3& v1)
{
	return v0.x * v1.x + v0.y * v1.y + v0.z * v1.z;
}
//---------------------------------------------------------------------------------
//	外積
//---------------------------------------------------------------------------------
void Vector3::cross(Vector3& v0, Vector3& v1)
{
	x = v0.y * v1.z - v0.z * v1.y;
	y = v0.z * v1.x - v0.x * v1.z;
	z = v0.x * v1.y - v0.y * v1.x;
}
//---------------------------------------------------------------------------------
//	DXライブラリで使う VECTOR を返す
//---------------------------------------------------------------------------------
VECTOR Vector3::VGet()
{
	VECTOR v;
	v.x = x;
	v.y = y;
	v.z = z;
	return v;
}
//---------------------------------------------------------------------------------
//	DXライブラリで使う VECTOR の値を取得して設定
//---------------------------------------------------------------------------------
void Vector3::VSet(VECTOR v)
{
	x = v.x;
	y = v.y;
	z = v.z;
}
